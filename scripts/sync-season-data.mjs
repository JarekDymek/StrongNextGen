import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'data', 'KGpo11.json');
const outputPath = path.join(root, 'src', 'season-data.js');
const checkOnly = process.argv.includes('--check');

const sourceText = await fs.readFile(sourcePath, 'utf8');
const season = JSON.parse(sourceText);
assert.equal(season.season, 2026, 'KGpo11.json musi opisywać sezon 2026');
assert.equal(season.maxCountedStarts, 4, 'Limit zaliczanych startów musi wynosić 4');
assert.equal(Array.isArray(season.events), true, 'KGpo11.json musi zawierać tablicę events');
assert.equal(season.events.length, 11, 'KGpo11.json musi zawierać dokładnie 11 imprez');

const generated = `// Generated from data/KGpo11.json. Do not edit this file manually.\nexport const DEFAULT_SEASON = ${JSON.stringify(season, null, 2)};\n`;
if (checkOnly) {
  const current = await fs.readFile(outputPath, 'utf8');
  assert.equal(current, generated, 'src/season-data.js nie odpowiada kanonicznemu data/KGpo11.json; uruchom npm run sync:season');
  console.log('Season runtime data matches data/KGpo11.json');
} else {
  await fs.writeFile(outputPath, generated, 'utf8');
  console.log(`Embedded ${season.events.length} season rounds from data/KGpo11.json`);
}
