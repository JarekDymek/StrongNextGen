import assert from 'node:assert/strict';
import { formatEventResult as format, calculateEventPoints } from '../src/scoring.js';
const bags = { name: 'Przerzucanie 6 worków nad poprzeczką 4,20 m', type: 'low' };
for (const [raw, expected] of [['19.20','6 na 6 worków — 19,20 s'],['119.82','5 na 6 worków — 19,82 s'],['130.36','5 na 6 worków — 30,36 s'],['132.88','5 na 6 worków — 32,88 s'],['235.81','4 na 6 worków — 35,81 s'],['239.74','4 na 6 worków — 39,74 s']]) assert.equal(format(raw, bags), expected);
assert.equal(format('0', bags), '0 na 6 worków');
const clock = { name: 'Zegar – 400 kg', type: 'high' };
assert.equal(format('155', clock), '155 minut');
assert.equal(format('60', clock), '60 minut');
assert.equal(format('DNF', {name:'Wyciskanie platformy na barki – 210 kg',type:'high'}), '0 powtórzeń');
const course = {name:'Spacer farmera na dystansie 40 m',type:'low'};
assert.equal(format('DNF',course),'0 metrów');
assert.equal(format('018.5',course),'18,5 m');
assert.equal(format('DNF+18.5m',course),'18,5 m');
assert.equal(format('1:12.5',course),'72,50 s');
assert.equal(format('',course),'—');
assert.equal(format('invalid',course),'—');
assert.equal(format('119.82',{name:'Przeciąganie lokomotywy',type:'low'}),'119,82 s');
const scored=calculateEventPoints([{id:'a',result:'19.20'},{id:'b',result:'119.82'}],2,'low');
const before=JSON.stringify(scored);
scored.results.forEach(row=>format(row,bags));
assert.equal(JSON.stringify(scored),before);
assert.deepEqual(scored.results.map(r=>r.points),['2.00','1.00']);
console.log('Result formatting tests passed');
