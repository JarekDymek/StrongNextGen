export function translate(locale, key) {
  const language = locale === 'en' ? 'en' : 'pl';
  return translations[language][key] || translations.pl[key] || key;
}

export function applyTranslations(root, locale) {
  const language = locale === 'en' ? 'en' : 'pl';
  document.documentElement.lang = language;
  document.title = translate(language, 'pageTitle');
  root.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = translate(language, element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    element.placeholder = translate(language, element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    element.setAttribute('aria-label', translate(language, element.dataset.i18nAriaLabel));
  });
}
